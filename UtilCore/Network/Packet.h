
//***************************************************************************
// Packet.h : 모든 네트워크 패킷이 공유하는 기본 헤더(프로토콜/서버 종류 무관)
//
//***************************************************************************

#ifndef UC_PACKET_H
#define UC_PACKET_H

#pragma pack(push, 1)

//***************************************************************************
// @brief 모든 네트워크 패킷의 기본 헤더.
// @details 프레이밍 규칙: 모든 패킷은 이 헤더로 시작하며, size는 "헤더를
//          포함한" 패킷 전체 크기다. 어떤 프로토콜(Chat/Game/Login 등)이든
//          이 규칙 하나만 지키면 CPacketDispatcher(PacketDispatcher.h)를
//          그대로 재사용할 수 있다 — 이 파일은 특정 서버/프로토콜을
//          전혀 모른다.
//***************************************************************************
struct PacketHeader
{
	uint16	size;	// 헤더 포함 패킷 전체 크기
	uint16	type;	// 패킷 타입 — 각 프로토콜이 정의한 enum을 uint16로 캐스팅해서 씀
};

#pragma pack(pop)

#endif // ndef UC_PACKET_H