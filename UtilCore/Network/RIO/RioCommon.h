#ifndef WIN32_LEAN_AND_MEAN
#define WIN32_LEAN_AND_MEAN
#endif

//***************************************************************************
// @brief 최소 지원 OS 버전 설정 (Windows 8 / Windows Server 2012 이상 - RIO API 지원)
//***************************************************************************
#ifndef _WIN32_WINNT
#define _WIN32_WINNT 0x0602
#endif

namespace Rio
{
    //**********************************************************************************************************************
    // @brief Shutdown 작업 수행 시 반환되는 결과 상태 코드
    //**********************************************************************************************************************
    enum class ShutdownResult : int32
    {
        Success = 0,        // 모든 Outstanding I/O Drain 완료 및 자원 정상 해제
        DrainTimeout = 1,   // 지정된 타임아웃 내에 Outstanding I/O가 0에 도달하지 못함
        CorruptCq = 2,      // CQ 오염(RIO_CORRUPT_CQ)으로 인해 비정상 종료됨
        InvalidCall = 3,    // 잘못된 호출Context (예: Dispatch 콜백 내부에서 Shutdown 호출)
        DispatchError = 4   // Shutdown 드레인 중 디스패치 또는 워커 스레드 오류 발생
    };

    //**********************************************************************************************************************
    // @brief CRioCore 엔진의 라이프사이클 상태 정의
    //**********************************************************************************************************************
    enum class State : int32
    {
        Uninitialized = 0,  // 초기화 전 상태
        Initializing = 1,    // 초기화 진행 중 상태
        Initialized = 2,    // CQ/IOCP 생성 및 초기화 완료 상태
        Running = 3,        // 워커 구동 중 및 I/O 제출/디스패치 정상 작동 상태
        Stopping = 4,       // 정지 요청 진입, 신규 I/O 제출 차단 및 Drain 시작 상태
        Stopped = 5,        // Outstanding I/O가 0에 도달하여 완전히 정지된 상태
        Faulted = 6,        // internal fault, CQ corruption 등 치명적 오류 발생 상태
        Closed = 7          // 모든 자원이 파괴되고 최종 닫힌 상태
    };

    //**********************************************************************************************************************
    // @brief 이벤트 수거 및 디스패치 모드
    //**********************************************************************************************************************
    enum class DispatchMode : int32
    {
        Wait = 0,   // 수거할 이벤트가 없을 경우 RIONotify 후 IOCP(GQCS) 대기 진입
        Drain = 1   // Shutdown 시 블로킹 대기 없이 잔여 이벤트만 비우고 즉시 반환
    };

    //**********************************************************************************************************************
    // @brief 슬롯의 할당 및 사용 상태를 정의하는 열거형
    //**********************************************************************************************************************
    enum class SlotState : uint8
    {
        Free = 0,           // 슬롯이 비어 있어 AllocSlot()을 통해 할당 가능한 상태
        Allocated = 1       // 슬롯이 할당되어 현재 사용 중인 상태(FreeSlot()을 통해서만 Free 상태로 전환 가능)
    };

    //***************************************************************************
    // @enum EEventState
    // @brief CRioEvent 객체의 디버그 및 메모리 상태 추적용 열거형입니다.
    // @details
    //      CRioEventPool 내 Free List의 보호 락(Lock) 내부에서만 상태가 변경되므로
    //      별도의 원자적 연산(std::atomic) 없이 안전하게 관리됩니다.
    //
    //      [Lifecycle Flow]
    //      Constructor -> Free <---> InUse
    //***************************************************************************
    enum class EEventState : uint8
    {
        Free = 0,   // 이벤트 객체가 풀(Pool)에 반납되어 재사용 가능한 상태
        InUse = 1   // 이벤트 객체가 할당되어 비동기 I/O 요청 처리에 사용 중인 상태
    };

    //***************************************************************************
    // @enum EventType
    // @brief 비동기 RIO I/O 작업의 유형을 정의하는 열거형입니다.
    // @details
    //      RIO 완료 통지(Completion) 이벤트가 발생했을 때 처리해야 할
    //      I/O 작업(수신/송신)의 종류를 구분하는 데 사용됩니다.
    //***************************************************************************
    enum class EventType : uint8
    {
        Receive = 0,    // 비동기 패킷 수신 요청 작업 (RIOReceive)
        Send = 1        // 비동기 패킷 송신 요청 작업 (RIOSend / RIOSendEx)
    };

    //***************************************************************************
    // @enum RioCqType
    // @brief Completion Queue 구분용 열거형
    //***************************************************************************
    enum class RioCqType : uint8
    {
        Receive,    // 수신 Completion Queue
        Send        // 송신 Completion Queue
    };

    //***************************************************************************
    // @enum SessionState
    // @brief RIO 세션의 라이프사이클 상태를 정의하는 열거형입니다.
    // @details
    //       세션의 생성부터 완전 종료까지의 원자적 상태 전이를 추적합니다.
    //***************************************************************************
    enum class SessionState : uint8
    {
        None = 0,    // 초기화되지 않은 미정의 상태
        Created,     // 세션 객체가 생성되어 메모리에 할당되었으나 아직 활성화되지 않은 상태
        Active,      // 연결이 활성화되어 I/O 요청 및 송수신 처리가 가능한 상태
        Closing,     // 종료 절차가 시작되어 신규 I/O 제출이 차단된 상태
        Closed       // 세션 연결이 완전 종료되고 정리 대기/완료된 상태
    };

    //***************************************************************************
    // @enum CloseReason
    // @brief 세션 종료 원인을 나타내는 열거형
    // @details
    //      - 네트워크 연결 해제, 내부 에러, 버퍼 관리 실패, 혹은 서버 관리자에 의한 강제 종료 등 
    //        세션이 닫히게 된 구체적인 원인을 기록하여 디버깅 및 모니터링에 활용합니다.
    //***************************************************************************
    enum class CloseReason
    {
        None,
        RemoteClosed,            // 상대방 연결 정상 종료
        SocketError,             // 소켓 네트워크 에러
        BufferAllocationFailed,  // RIO 버퍼 슬롯 할당 실패
        EventPoolExhausted,      // RIO 이벤트 풀 고갈
        ReceivePostFailed,       // Receive 요청 실패
        SendPostFailed,          // Send 요청 실패
        RingBufferOverflow,      // 수신 링버퍼 오버플로우
        SendBufferOverflow,      // 송신 링버퍼 오버플로우
        InvalidPacketHeader,     // 비정상 패킷 헤더
        InternalError,           // 기타 내부 처리 에러
        ForcedClose              // 서버 측 강제 종료
    };

    //***************************************************************************
    // @enum ServerState
    // @brief 서버 엔진의 동작 라이프사이클 상태를 정의하는 열거형입니다.
    // @details
    //      서버 인스턴스의 생성부터 리소스 완전 해제까지의 구동 상태 전이를 관리합니다.
    //***************************************************************************
    enum class ServerState : uint8
    {
        Created = 0,    // 서버 객체가 생성되었으나 초기화되지 않은 상태
        Initialized,    // RIO 커널 자원 및 네트워크 바인딩 초기화가 완료된 상태
        Running,        // I/O 완료 통지 루프 및 서비스가 정상 동작 중인 상태
        Stopping,       // 서버 정지 요청을 받아 세션 CloseAll 및 잔여 I/O 정리를 진행 중인 상태
        Stopped,        // 모든 세션 정리 및 네트워크 I/O 처리가 안전하게 정지된 상태
        Shutdown        // 서버 할당 자원이 완벽히 해제되고 최종 종료된 상태
    };

    //******************************************************************************************************************
    // @brief 한 번의 RIODequeueCompletion() 호출에서 수거할 최대 completion 수
    //******************************************************************************************************************
    static constexpr ULONG kBatchSize = 64;

    //***************************************************************************
    // @brief DispatchBatch 및 내부 처리 반환용 오류/상태 상숫값
    //***************************************************************************
    static constexpr int32 kCorruptCq = -1;             // CQ 오염 발생 (RIO_CORRUPT_CQ)
    static constexpr int32 kStopped = -2;               // Core 엔진 정지 완료
    static constexpr int32 kNotifyError = -3;           // RIONotify 호출 실패
    static constexpr int32 kIocpError = -4;             // GetQueuedCompletionStatus 오류 발생
    static constexpr int32 kInvalidCompletion = -5;     // 유효하지 않은 완료 패킷 수신

    //***************************************************************************
    // @brief IOCP CompletionKey 구분용 식별 비트 태그 (Tag Mask)
    //***************************************************************************
    constexpr ULONG_PTR kReceiveCompletionTag = 0x01;   // 수신 Completion 이벤트 비트 태그
    constexpr ULONG_PTR kSendCompletionTag = 0x02;      // 송신 Completion 이벤트 비트 태그
    constexpr ULONG_PTR kCompletionTagMask = 0x03;      // Completion 태그 마스크

    //***************************************************************************
    // @brief 기본 Drain 대기 타임아웃 (5초)
    //***************************************************************************
    static constexpr std::chrono::milliseconds kDefaultDrainTimeout{ 5000 };

    //**********************************************************************************************************************
    // @brief 유효하지 않은 슬롯 인덱스를 나타내는 센티널(Sentinel) 상숫값
    // @details AllocSlot() 등의 함수가 슬롯 할당 실패 시 반환하거나, 초기화되지 않은 슬롯 인덱스를
    //          표시할 때 사용합니다. uint32_t의 최댓값(0xFFFFFFFFu, UINT32_MAX)을 가리킵니다.
    //**********************************************************************************************************************
    static constexpr uint32 kInvalidSlotIndex = 0xFFFFFFFFu;

    //***************************************************************************
    // @brief Accept 폴링 주기
    // @details
    //      Accept 루프에서 클라이언트 접속이 없을 때 대기할 시간 간격을 정의합니다.
    //***************************************************************************
    constexpr std::chrono::milliseconds kAcceptPollInterval(1);

    //***************************************************************************
    // @brief Listen 소켓 Backlog 최소 값
    // @details
    //      Listen 소켓 생성 시 설정 가능한 연결 대기 큐(Backlog)의 최소 허용치입니다.
    //***************************************************************************
    constexpr int32 kListenBacklogMinimum = 1;

    //***************************************************************************
    // @brief RIO 기본 버퍼 및 I/O 제한 설정 상수
    //***************************************************************************
    constexpr uint32   kMaxOutstandingIo = 1024;    // 최대 동시 비동기 I/O 처리 요청 수
    constexpr uint32   kRecvBufferSlotSize = 8192;  // 수신 버퍼 슬롯 당 크기 (바이트 단위, 예: 8KB)
    constexpr size_t   kDefaultAlignment = 64;      // 메모리 정렬 기본 단위 (캐시라인 최적화용 64바이트)

    //***************************************************************************
    // @brief 세션 매니저에서 락 경합을 최소화하기 위해 분산 처리할 클러스터 개수.
    // @details
    // [클러스터 개수 최적화 가이드 및 선정 이유]
    // - 2의 제곱수 최적화: 16은 2의 제곱수($2^4$)이므로, 내부 해시 인덱스 연산(key % kSessionClusterCnt) 시 
    //   컴파일러가 느린 나눗셈 대신 매우 빠른 비트 연산(key & (kSessionClusterCnt - 1))으로 자동 최적화합니다.
    // - 락 경합 대폭 완화: 단일 락 구조 대비 동시 접근 시 충돌 확률을 1/16 수준으로 줄여줍니다.
    // - 코어 구조와의 조화: 일반적인 8~16코어(하이퍼스레딩 포함 16~32스레드) 상용 서버 환경에서 
    //   워커 스레드들이 서로 다른 락을 참조할 확률을 높여 병목을 효과적으로 해소합니다.
    // [예시]
    //		- 대규모 하이엔드 서버 환경(32코어 이상, 수천 명 동접)의 경우 클러스터 개수를 32 또는 64로 늘려 부하를 분산하는 것을 권장
    //		- 소규모 서버 또는 테스트 환경(2 ~ 4코어)의 경우 클러스터 개수를 8 또는 16
    //***************************************************************************
    static constexpr int32 kSessionClusterCnt = 16;

    //***************************************************************************
    // @brief 최대 패킷 크기 (8KB)
    // @details 네트워크를 통해 수신하거나 처리할 수 있는 단일 패킷의 최대 바이트 허용 크기입니다.
    //***************************************************************************
    constexpr uint16 kMaxPacketSize = 8192;

    //***************************************************************************
    // @brief 송신 링버퍼 크기 (65536 바이트 = 64KB)
    // @details 
    //      - 클라이언트로 전송할 패킷 데이터를 임시 큐잉 및 직렬화하기 위해 세션마다 할당되는 송신 링버퍼의 용량입니다.
    //      - [최적화 및 용량 선정 이유]
    //        1. 송신 버스트(Burst) 대응: 
    //           게임 서버나 실시간 통신에서 일시에 대량의 패킷을 전송(Broadcast 등)할 때 
    //           네트워크 카드(NIC) 전송 속도보다 애플리케이션의 생성 속도가 빠른 경우 발생할 수 있는 
    //           지연과 블로킹을 완충(Buffer)해 주는 안전 자산 역할을 합니다.
    //        2. 비트 연산 최적화: 
    //           2의 제곱수($2^{16}$)로 설계되어 포인터 링 랩어라운드(Wrap-around) 연산 시 
    //           비트 마스킹을 통한 고속 연산이 가능하여 CPU 오버헤드를 최소화합니다.
    //***************************************************************************
    constexpr size_t kSendRingBufferSize = 65536;

    //***************************************************************************
    // @brief 수신 링버퍼 크기 (65536 바이트 = 64KB)
    // @details 
    //      - 네트워크 소켓으로부터 비동기 수신(RIOReceive)된 원본 바이트 스트림을 조각 단위로 
    //        누적하고, 패킷 파싱(Framing)을 수행하기 위해 세션마다 할당되는 수신 링버퍼의 용량입니다.
    //      - [최적화 및 용량 선정 이유]
    //        1. TCP 스트림 분할/병합 처리: 
    //           TCP는 경계가 없는 스트림 프로토콜이므로 패킷이 쪼개져서(Fragmentation) 들어오거나 
    //           여러 패킷이 한 번에 뭉쳐서(Clumping) 들어올 수 있습니다. 64KB 링버퍼는 이러한 
    //           불규칙한 네트워크 청크(Chunk) 데이터를 안정적으로 흡수합니다.
    //        2. 메모리 사용량 균형: 
    //           수천 개 이상의 동시 접속 세션 환경에서 각 세션당 64KB의 수신/송신 버퍼는 
    //           서버 전체 메모리(RAM) 효율성을 해치지 않으면서도 안정적인 패킷 디코딩을 보장합니다.
    //***************************************************************************
    constexpr size_t kRecvRingBufferSize = 65536;
}

