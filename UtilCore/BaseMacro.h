#define SERVER_CONFIG						CServerConfig::GetSingletonPtr()

//***************************************************************************
// @brief Null 포인터 참조를 발생시켜 의도적으로 크래시를 유발합니다.
// @note 치명적인 오류 발생 시 즉시 프로세스를 종료하고 덤프를 남기기 위해 사용합니다.
//***************************************************************************
#define CRASH								{ char *p = 0; *p = 1; }

//***************************************************************************
// @brief 동적 할당된 단일 객체 메모리를 안전하게 해제하고 nullptr로 초기화합니다.
// @param p 해제할 포인터
//***************************************************************************
#define SAFE_DELETE(p)						{ if ( p ) delete p; p = nullptr; } 

//***************************************************************************
// @brief 동적 할당된 배열 메모리를 안전하게 해제하고 nullptr로 초기화합니다.
// @param p 해제할 배열 포인터
//***************************************************************************
#define SAFE_DELETE_ARRAY(p)				{ if ( p ) delete[] p; p = nullptr; }

//***************************************************************************
// @brief 특정 크래시 원인 정보를 명시하며 덤프 생성을 위한 크래시를 발생시킵니다.
// @param cause 크래시 발생 원인 설명 문자열
// @note 0xDEADBEEF 주소 참조를 통해 덤프 분석 시 원인을 명확히 파악할 수 있도록 합니다.
//***************************************************************************
#define CRASH_CAUSE(cause)						\
{											\
	uint32* crash = nullptr;				\
	__analysis_assume(crash != nullptr);	\
	*crash = 0xDEADBEEF;					\
}

//***************************************************************************
// @brief 조건식이 거짓일 경우 크래시를 발생시키는 단정문(Assert)입니다.
// @param expr 검증할 조건식
// @note 조건식이 false인 경우 CRASH_CAUSE를 호출하여 즉시 종료시킵니다.
//***************************************************************************
#define ASSERT_CRASH(expr)			\
{									\
	if (!(expr))					\
	{								\
		CRASH_CAUSE("ASSERT_CRASH");		\
		__analysis_assume(expr);	\
	}								\
}

//***************************************************************************
// @brief Windows OS 버전에 따라 알맞은 Tick Count 함수를 매핑합니다.
// @return DWORD/ULONGLONG 시스템 기동 후 경과된 시간(ms)
// @note Windows Vista 이상(_WIN32_WINNT >= 0x0600)에서는 49.7일 오버플로우 문제를 방지하기 위해 GetTickCount64를 사용합니다.
//***************************************************************************
#if (_WIN32_WINNT >= 0x0600)
#define _GetTickCount	GetTickCount64
#else
#define _GetTickCount	GetTickCount
#endif

//***************************************************************************
// @brief 디버그 빌드 환경에서 메모리 오버런/언더런 검출용 스톰프 할당자(Stomp Allocator)를 자동 활성화합니다.
// @note
// [작동 방식]
// - _DEBUG 플래그가 정의되어 있고, _STOMP 매크로가 사전 정의되지 않은 경우에만 
//   _STOMP를 자동으로 정의하여 디버그 할당자로 전환합니다.
// - 메모리 경계 침범(오버런/언더런) 및 Use-After-Free 버그를 디버그 단계에서 
//	 즉시 검출하기 위해 사용됩니다.
// - 릴리즈(Release) 빌드에서는 무시되므로 성능 하락 없이 디버그 환경에서만
//   메모리 오염 및 Out-of-Bounds 에러를 빠르게 추적할 수 있습니다.
//***************************************************************************
#if defined(_DEBUG) && !defined(_STOMP)
#define _STOMP
#endif

//***************************************************************************
// @brief 빌드 타겟(x86/x64) 및 빌드 모드(Debug/Release)에 맞는 라이브러리 파일명을 생성합니다.
// @param LIB 확장자를 제외한 기본 라이브러리 이름 (예: "MyLib")
// @return const char* 매핑된 .lib 파일명 문자열
//***************************************************************************
#ifdef _WIN64
#	ifdef _DEBUG
#		define LIB_NAME(LIB) LIB##"64D.lib"
#	else
#		define LIB_NAME(LIB) LIB##"64.lib"
#	endif
#else
#	ifdef _DEBUG
#		define LIB_NAME(LIB) LIB##"32D.lib"
#	else
#		define LIB_NAME(LIB) LIB##"32.lib"
#	endif
#endif

//***************************************************************************
// @brief 클래스 전방 선언(Forward Declaration)과 함께 스마트 포인터 타입 별칭을 자동 생성하는 매크로
// 
// [작동 방식]
// - 'class name' 형태로 전방 선언을 동시에 수행하므로, 별도의 헤더 파일 include 없이도
//   스마트 포인터 타입 별칭(예: CJob -> CJobRef)을 안전하게 사용할 수 있습니다.
// - 템플릿 인스턴스화 시 불투명 타입(Incomplete Type) 상태를 활용하여 컴파일 타임 
//   헤더 의존성 및 순환 참조(Circular Dependency)를 최소화합니다.
// 
// [사용 예시]
// - USING_SHARED_PTR(CJob); -> using CJobRef = std::shared_ptr<class CJob>;
//***************************************************************************
#define USING_SHARED_PTR(name)	using name##Ref = std::shared_ptr<class name>;

//***************************************************************************
// 배열 크기 및 바이트 크기 계산용 유틸리티 매크로
//***************************************************************************
#define size16(val)		static_cast<int16>(sizeof(val))
#define size32(val)		static_cast<int32>(sizeof(val))
#define len16(arr)		static_cast<int16>(sizeof(arr)/sizeof(arr[0]))
#define len32(arr)		static_cast<int32>(sizeof(arr)/sizeof(arr[0]))

#endif // ndef UC_BASEMACRO_H