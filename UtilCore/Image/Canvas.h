
//***************************************************************************
// Canvas.h : interface for the CCanvas class.
//
//***************************************************************************

#ifndef UC_CANVAS_H
#define UC_CANVAS_H

#include "ImageTypes.h"
#include "Sprite.h"

//***************************************************************************
// @brief ImageBuffer를 내부 캔버스로 사용하는 Canvas 클래스
//***************************************************************************
class CCanvas
{
public:
	CCanvas();
	~CCanvas();

	//***************************************************************************
	// @brief 지정한 크기로 Canvas 버퍼 생성 및 초기화
	// @param nWidth 가로 크기(픽셀)
	// @param nHeight 세로 크기(픽셀)
	//***************************************************************************
	void Init(int nWidth, int nHeight);
	void Close();

	//***************************************************************************
	// @brief 스프라이트를 캔버스에 드로잉 (컬러 및 알파 데이터 반영)
	// @param pSprite 스프라이트 객체 포인터
	// @param x 렌더링 시작 X 좌표
	// @param y 렌더링 시작 Y 좌표
	// @param nIndex 스프라이트 프레임 인덱스
	//***************************************************************************
	void DrawImage(CSprite* pSprite, int x, int y, int nIndex);
	void DrawAlpha(CSprite* pSprite, int x, int y, int nIndex);

	//***************************************************************************
	// @brief 영역 자르기
	// @param rRect 잘라낼 RECT 영역
	// @return 처리 성공 여부
	//***************************************************************************
	BOOL Crop(RECT rRect);

	//***************************************************************************
	// @brief 좌우 반전
	// @return 처리 성공 여부
	//***************************************************************************
	BOOL MirrorImage();

	//***************************************************************************
	// @brief 알파값이 0인 영역의 RGB 값을 투명색(0,0,0,0)으로 필터링
	//***************************************************************************
	void FilterImage();

	//***************************************************************************
	// @brief Canvas(ImageBuffer)를 지정한 이미지 포맷의 바이트 버퍼로 인코딩
	// @param outBuffer 인코딩된 바이트 데이터가 저장될 vector
	// @param format 저장할 이미지 포맷 (기본값: ImageFormat::PNG)
	// @return 인코딩 성공 시 버퍼 바이트 크기, 실패 시 0
	//***************************************************************************
	int Encode(std::vector<uint8_t>& outBuffer, ImageFormat format = ImageFormat::PNG);

	//***************************************************************************
	// @brief C-Style 외부 호환용 (동적 할당 버퍼 생성)
	// @param pbBuffer 할당된 버퍼 포인터 참조 (호출 측에서 delete[] 필요)
	// @param format 저장할 이미지 포맷 (기본값: ImageFormat::PNG)
	// @return 인코딩 성공 시 버퍼 바이트 크기, 실패 시 0
	//***************************************************************************
	int Encode(BYTE*& pbBuffer, ImageFormat format = ImageFormat::PNG);

	//***************************************************************************
	// @brief 내부 ImageBuffer 객체 참조 반환
	// @return ImageBuffer 객체 참조
	//***************************************************************************
	ImageBuffer& GetBuffer() { return m_canvas; }
	const ImageBuffer& GetBuffer() const { return m_canvas; }

public:
	ImageBuffer m_canvas; // RGBA8 캔버스 버퍼
};

#endif // ndef UC_CANVAS_H