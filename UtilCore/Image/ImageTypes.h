
#ifndef UC_IMAGETYPES_H
#define UC_IMAGETYPES_H

#include <cstdint>
#include <vector>
#include <string>
#include <stdexcept>
#include <memory>

//***************************************************************************
// @brief 픽셀 하나를 구성하는 채널 구성과 채널당 바이트 배치를 나타내는 열거형
// @details RGBA8은 라이브러리 내부 표준 포맷이며, RGB8/GRAY8은 입출력 편의를
//          위한 보조 포맷이다.
//***************************************************************************
enum class PixelFormat : uint8_t
{
	RGBA8,   // 4 bytes/pixel - 내부 표준 포맷
	RGB8,    // 3 bytes/pixel - 입출력 편의용 (알파 없음)
	GRAY8,   // 1 byte/pixel  - 그레이스케일
};

int BytesPerPixel(PixelFormat fmt);

//***************************************************************************
// @brief ImageIO가 인식/처리할 수 있는 이미지 파일 포맷 종류
// @details 새 포맷 코덱을 추가할 때 이 열거형에 항목을 추가하고
//          ImageIO의 코덱 레지스트리에 등록한다.
//***************************************************************************
enum class ImageFormat
{
	Unknown, // 인식되지 않은 포맷
	BMP,     // Windows 비압축 BMP
	PNG,     // PNG (8bit, non-interlaced)
	JPEG,    // JPEG (baseline sequential DCT)
};

//***************************************************************************
// @brief 이미지 로드/디코드/인코드 과정에서 발생하는 오류를 나타내는 예외 클래스
// @details std::runtime_error를 상속하여 what()으로 오류 메시지를 전달한다.
//***************************************************************************
class ImageException : public std::runtime_error
{
public:
	//***************************************************************************
	// @brief 예외 메시지를 설정하여 생성
	// @param msg 예외 메시지 문자열
	//***************************************************************************
	explicit ImageException(const std::string& msg) : std::runtime_error(msg) {}
};

//***************************************************************************
// @brief 항상 RGBA8(top-down, row-major)로 픽셀을 보관하는 이미지 중간 표현
// @details 모든 코덱의 Decode() 결과와 Encode()의 입력은 이 클래스를 사용한다.
//          코덱은 각자의 파일 포맷 <-> ImageBuffer 간 변환만 책임지고,
//          필터/색공간 변환은 ImageBuffer만 다루므로 포맷에 독립적이다.
//***************************************************************************
class ImageBuffer
{
public:
	//***************************************************************************
	// @brief 빈(0x0) 이미지 버퍼로 기본 생성
	//***************************************************************************
	ImageBuffer() = default;

	ImageBuffer(uint32_t width, uint32_t height);

	//***************************************************************************
	// @brief 이미지 가로 크기(픽셀)를 반환
	// @return 가로 크기(픽셀)
	//***************************************************************************
	uint32_t Width() const { return width_; }

	//***************************************************************************
	// @brief 이미지 세로 크기(픽셀)를 반환
	// @return 세로 크기(픽셀)
	//***************************************************************************
	uint32_t Height() const { return height_; }

	//***************************************************************************
	// @brief 전체 픽셀 개수를 반환
	// @return width * height 픽셀 개수
	//***************************************************************************
	size_t PixelCount() const { return static_cast<size_t>(width_) * height_; }

	//***************************************************************************
	// @brief 이미지가 비어 있는지(가로/세로가 0인지) 확인
	// @return 비어 있으면 true
	//***************************************************************************
	bool Empty() const { return width_ == 0 || height_ == 0; }

	//***************************************************************************
	// @brief 픽셀 원시 버퍼에 대한 쓰기 가능한 포인터를 반환
	// @return RGBA8 픽셀 데이터의 시작 주소
	//***************************************************************************
	uint8_t* Data() { return pixels_.data(); }

	//***************************************************************************
	// @brief 픽셀 원시 버퍼에 대한 읽기 전용 포인터를 반환
	// @return RGBA8 픽셀 데이터의 시작 주소
	//***************************************************************************
	const uint8_t* Data() const { return pixels_.data(); }

	//***************************************************************************
	// @brief 픽셀 원시 버퍼의 전체 바이트 크기를 반환
	// @return width * height * 4 바이트
	//***************************************************************************
	size_t DataSize() const { return pixels_.size(); }

	uint8_t* At(uint32_t x, uint32_t y);
	const uint8_t* At(uint32_t x, uint32_t y) const;

	void SetPixel(uint32_t x, uint32_t y, uint8_t r, uint8_t g, uint8_t b, uint8_t a = 255);
	void Resize(uint32_t width, uint32_t height);
	ImageBuffer Clone() const;

private:
	uint32_t width_ = 0;             // 이미지 가로 크기(픽셀)
	uint32_t height_ = 0;            // 이미지 세로 크기(픽셀)
	std::vector<uint8_t> pixels_;    // RGBA8 픽셀 데이터, top-down row-major
};

#endif // ndef UC_IMAGETYPES_H
