
//***************************************************************************
// DBAsyncSrv.h : interface for the CDBAsyncSrv class.
//
//***************************************************************************

#ifndef UC_DBASYNCSRV_H
#define UC_DBASYNCSRV_H

#pragma pack(push, 1)

#include <Memory/Allocator.h>

//***************************************************************************
// @brief 비동기 DB 요청 베이스 구조체
// @detail BaseAllocator를 상속받아 오버라이드된 operator new/delete를 사용하며,
//         모든 파생 요청 구조체가 자동으로 메모리 할당기를 타도록 설계된 1바이트 패킹 구조체입니다.
//***************************************************************************
struct st_DBAsyncRq : public BaseAllocator
{
	//***************************************************************************
	// @brief st_DBAsyncRq 기본 생성자입니다.
	//***************************************************************************
	st_DBAsyncRq()
	{
		callIdent = 0;
		bReTry = false;
	}

	//***************************************************************************
	// @brief st_DBAsyncRq 가상 소멸자입니다. 파생 구조체의 올바른 소멸과 메모리 누수를 방지합니다.
	//***************************************************************************
	virtual ~st_DBAsyncRq() {
		//LOG_ERROR(_T("Delete st_DBAsyncRq")); 
	}

	BYTE	callIdent; // 핸들러 식별자
	bool	bReTry;    // 재시도 여부
};

//***************************************************************************
// @brief 비동기 DB 응답 베이스 구조체
// @detail BaseAllocator를 상속받아 오버라이드된 operator new/delete를 사용하며,
//         모든 파생 응답 구조체가 자동으로 메모리 할당기를 타도록 설계된 1바이트 패킹 구조체입니다.
//***************************************************************************
struct st_DBAsyncRp : public BaseAllocator
{
	//***************************************************************************
	// @brief st_DBAsyncRp 기본 생성자입니다.
	//***************************************************************************
	st_DBAsyncRp()
	{
		callIdent = 0;
		pthis = nullptr;
	}

	//***************************************************************************
	// @brief st_DBAsyncRp 가상 소멸자입니다.
	//***************************************************************************
	virtual ~st_DBAsyncRp() {
		LOG_ERROR(_T("Delete st_DBAsyncRp"));
	}

	BYTE			callIdent; // 핸들러 식별자
	st_DBAsyncRp* pthis;     // Self 응답 객체 포인터
};

#pragma pack(pop)

//***************************************************************************
// @brief 비동기 DB 요청 처리를 위한 핸들러 인터페이스 클래스
// @detail 파생 클래스에서 ProcessAsyncCall을 구현하여 명령 식별자에 맞는 비동기 로직을 수행합니다.
//***************************************************************************
class CDBAsyncSrvHandler
{
public:
	//***************************************************************************
	// @brief CDBAsyncSrvHandler 기본 생성자입니다.
	//***************************************************************************
	CDBAsyncSrvHandler() {}

	//***************************************************************************
	// @brief CDBAsyncSrvHandler 가상 소멸자입니다.
	//***************************************************************************
	virtual ~CDBAsyncSrvHandler() {}

	virtual EDBReturnType ProcessAsyncCall(st_DBAsyncRq* pStAsync) = 0;
};

#endif // ndef UC_DBASYNCSRV_H